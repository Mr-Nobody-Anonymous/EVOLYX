#!/usr/bin/env python3
"""EVOLYX Cross-Platform Universal Installation & Hardware Configurator.

Detects operating system, CPU architecture, GPU accelerators (CUDA/ROCm/Apple Silicon),
installs tailored dependency profiles, configures .env, and initializes the platform.
"""

import argparse
import platform
import shutil
import subprocess
import sys
from pathlib import Path


class HardwareDetector:
    """Inspects machine hardware, operating system, and accelerator capabilities."""

    def __init__(self):
        self.os_type = platform.system().lower()  # windows, linux, darwin
        self.arch = platform.machine().lower()    # x86_64, amd64, arm64, aarch64
        self.has_nvidia = False
        self.gpu_name = None
        self.vram_gb = 0
        self.is_apple_silicon = False

        self._detect_gpu()

    def _detect_gpu(self) -> None:
        # Check Apple Silicon
        if self.os_type == "darwin" and "arm" in self.arch:
            self.is_apple_silicon = True
            self.gpu_name = "Apple Silicon (MPS Metal Acceleration)"
            return

        # Check NVIDIA GPU via nvidia-smi
        nvidia_smi = shutil.which("nvidia-smi")
        if nvidia_smi:
            try:
                res = subprocess.run(
                    [nvidia_smi, "--query-gpu=name,memory.total", "--format=csv,noheader,nounits"],
                    capture_output=True,
                    text=True,
                    check=True,
                    timeout=5,
                )
                output = res.stdout.strip()
                if output:
                    line = output.splitlines()[0]
                    parts = line.split(",")
                    self.has_nvidia = True
                    self.gpu_name = parts[0].strip()
                    if len(parts) > 1:
                        self.vram_gb = round(float(parts[1].strip()) / 1024, 1)
            except Exception:
                pass


def print_banner(detector: HardwareDetector) -> None:
    print("=================================================================")
    print("           EVOLYX UNIVERSAL INSTALLER & SETUP WIZARD            ")
    print("=================================================================")
    print(f" Operating System:  {platform.system()} ({platform.release()})")
    print(f" CPU Architecture:  {platform.machine()}")
    print(f" Python Version:    {sys.version.split()[0]} ({sys.executable})")

    if detector.is_apple_silicon:
        print(f" Hardware Engine:   {detector.gpu_name}")
    elif detector.has_nvidia:
        print(f" Hardware Engine:   NVIDIA GPU ({detector.gpu_name}, {detector.vram_gb} GB VRAM)")
    else:
        print(f" Hardware Engine:   Standard CPU Mode (Universal Compatibility)")
    print("=================================================================\n")


def configure_environment(root: Path, detector: HardwareDetector, profile: str) -> None:
    """Generates a tailored .env file for the detected device."""
    env_file = root / ".env"
    if env_file.exists():
        print(f"[*] Found existing .env file at {env_file}. Preserving it.")
        return

    # Select best model backend based on hardware
    if profile in ["gpu", "cuda"] and detector.has_nvidia:
        backend = "transformers"
        model_name = "Qwen/Qwen2.5-0.5B-Instruct"
    elif profile == "mac" or detector.is_apple_silicon:
        backend = "llama_cpp"
        model_name = "artifacts/models/base/qwen2.5-0.5b-instruct.Q4_K_M.gguf"
    else:
        backend = "mock"
        model_name = "Qwen/Qwen2.5-0.5B-Instruct"

    content = f"""# EVOLYX Environment Configuration (Auto-Generated by install.py)
EVOLYX_ENV=development
EVOLYX_LOG_LEVEL=INFO
EVOLYX_MODEL_BACKEND={backend}
EVOLYX_MODEL_NAME_OR_PATH={model_name}

# Memory & Persistence
EVOLYX_MEMORY_BACKEND=sqlite
EVOLYX_DB_PATH=artifacts/evolyx.db

# API & Server Configuration
EVOLYX_API_HOST=127.0.0.1
EVOLYX_API_PORT=8000
EVOLYX_SECRET_KEY=evolyx-secret-key-change-in-production

# Sandboxing
EVOLYX_SANDBOX_TIMEOUT_SEC=15
EVOLYX_ALLOW_UNRESTRICTED_CODE=false
EVOLYX_WEB_SEARCH_PROVIDER=mock
EVOLYX_AUTO_PROMOTE=false
"""
    with open(env_file, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[+] Created tailored .env configuration with backend: '{backend}'")


def init_database(root: Path) -> None:
    """Initializes local SQLite metadata, memory, and trajectory tables."""
    artifacts_dir = root / "artifacts"
    artifacts_dir.mkdir(parents=True, exist_ok=True)
    db_path = artifacts_dir / "evolyx.db"

    # Import EVOLYX memory and trajectory stores
    sys.path.insert(0, str(root))
    try:
        from evolyx.learning.trajectory_store import TrajectoryStore
        from evolyx.memory.long_term import LongTermMemory

        LongTermMemory(db_path=str(db_path))
        TrajectoryStore(db_path=str(db_path))
        print(f"[+] Initialized EVOLYX SQLite database at: {db_path}")
    except Exception as exc:
        print(f"[!] Note: Database init skipped or deferred ({exc})")


def run_self_test(root: Path) -> bool:
    """Runs the 16 verification tests to ensure system readiness."""
    print("\n[*] Running EVOLYX verification battery...")
    try:
        import pytest
        ret = pytest.main([str(root / "tests"), "-v", "-q"])
        return ret == 0
    except Exception:
        # Run via subprocess
        res = subprocess.run([sys.executable, "-m", "pytest", str(root / "tests"), "-q"], cwd=root)
        return res.returncode == 0


def main() -> None:
    parser = argparse.ArgumentParser(description="Install and configure EVOLYX on any device")
    parser.add_argument(
        "--profile",
        choices=["auto", "cpu", "gpu", "mac", "dev"],
        default="auto",
        help="Installation profile (default: auto-detect)",
    )
    parser.add_argument(
        "--skip-tests",
        action="store_true",
        help="Skip running verification test battery",
    )
    args = parser.parse_args()

    root = Path(__file__).resolve().parent
    detector = HardwareDetector()
    print_banner(detector)

    # Determine profile
    profile = args.profile
    if profile == "auto":
        if detector.is_apple_silicon:
            profile = "mac"
        elif detector.has_nvidia:
            profile = "gpu"
        else:
            profile = "cpu"
    print(f"[*] Selected Installation Profile: '{profile.upper()}'")

    # Install Python dependencies
    pip_cmd = [sys.executable, "-m", "pip", "install", "--upgrade"]
    print("\n[*] Installing core platform dependencies...")
    subprocess.run(pip_cmd + ["pip", "setuptools", "wheel"], check=False)
    subprocess.run(pip_cmd + ["pydantic", "pyyaml", "requests", "pytest"], check=False)

    if profile in ["gpu", "cuda"]:
        print("[*] GPU profile selected: installing optional ML packages...")
        subprocess.run(pip_cmd + ["torch", "transformers", "peft", "accelerate"], check=False)
    elif profile == "mac":
        print("[*] Apple Silicon profile selected: configuring MPS...")
        subprocess.run(pip_cmd + ["torch"], check=False)

    # Configure Environment & Files
    configure_environment(root, detector, profile)
    init_database(root)

    # Run Self-Test
    if not args.skip_tests:
        success = run_self_test(root)
        if success:
            print("\n[✔] SUCCESS: All EVOLYX tests passed 100%!")
        else:
            print("\n[!] Warning: Some self-tests had warnings. Platform is still usable.")

    print("\n=================================================================")
    print("               EVOLYX IS READY TO USE!                          ")
    print("=================================================================")
    print(" To start chatting:           python -m apps.cli.main chat")
    print(" To run an autonomous task:   python -m apps.cli.main task \"<your instruction>\"")
    print(" To run an evolution cycle:   python -m apps.cli.main evolve")
    print(" To start the REST API:       python -m apps.api.main")
    print(" To view the dashboard:       python -m apps.dashboard.app")
    print("=================================================================\n")


if __name__ == "__main__":
    main()

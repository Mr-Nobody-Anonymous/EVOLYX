"""Hierarchical task planner for EVOLYX runtime."""

import json
import logging
import re
from typing import Any, Dict, List, Optional
from evolyx.core.interfaces import ModelBackend
from evolyx.core.prompts import TASK_PLANNING_PROMPT
from evolyx.core.schemas import IntentType, MemoryRecord, Message, Plan, PlanStep

logger = logging.getLogger(__name__)


class Planner:
    """Creates structured execution plans for complex tasks."""

    def __init__(self, model: Optional[ModelBackend] = None):
        self.model = model

    def create_plan(
        self,
        message: str,
        intent: IntentType,
        memories: Optional[List[MemoryRecord]] = None,
        available_tools: Optional[List[Dict[str, Any]]] = None,
    ) -> Plan:
        """Generates an actionable multi-step plan."""
        memories = memories or []
        available_tools = available_tools or []

        # If direct answer, single synthesis step
        if intent == IntentType.DIRECT_ANSWER:
            return Plan(
                intent=intent,
                reasoning="Direct conversational request. No external tools needed.",
                steps=[
                    PlanStep(
                        step_id=1,
                        description="Formulate direct response using current model knowledge.",
                        tool_name=None,
                    )
                ],
                confidence=1.0,
            )

        # If LLM model is available, prompt for plan
        if self.model and available_tools:
            try:
                tools_desc = "\n".join(
                    f"- {t.get('name')}: {t.get('description')}" for t in available_tools
                )
                mems_desc = "\n".join(f"- [{m.kind.value}] {m.content}" for m in memories) or "None"
                prompt = TASK_PLANNING_PROMPT.format(
                    available_tools=tools_desc,
                    memories=mems_desc,
                    message=message,
                    intent=intent.value,
                )
                response = self.model.generate([Message(role="user", content=prompt)], temperature=0.2)
                match = re.search(r"\{.*\}", response, re.DOTALL)
                if match:
                    data = json.loads(match.group(0))
                    raw_steps = data.get("steps", [])
                    steps = [
                        PlanStep(
                            step_id=s.get("step_id", i + 1),
                            description=s.get("description", "Execute step"),
                            tool_name=s.get("tool_name"),
                            tool_arguments=s.get("tool_arguments", {}),
                            depends_on=s.get("depends_on", []),
                        )
                        for i, s in enumerate(raw_steps)
                    ]
                    if steps:
                        return Plan(
                            intent=intent,
                            reasoning=data.get("reasoning", "Generated by LLM planner"),
                            steps=steps,
                            confidence=0.9,
                        )
            except Exception as exc:
                logger.warning("LLM planning failed, using deterministic strategy: %s", exc)

        # Deterministic fallback plan based on intent
        return self._fallback_plan(intent, message)

    def _fallback_plan(self, intent: IntentType, message: str) -> Plan:
        """Provides a safe deterministic fallback plan."""
        if intent == IntentType.RESEARCH_AND_RETRIEVE:
            steps = [
                PlanStep(
                    step_id=1,
                    description="Search documentation and web sources for relevant knowledge.",
                    tool_name="web_search",
                    tool_arguments={"query": message},
                ),
                PlanStep(
                    step_id=2,
                    description="Synthesize findings and provide verified answer.",
                    tool_name=None,
                    depends_on=[1],
                ),
            ]
            return Plan(intent=intent, reasoning="Retrieve then synthesize.", steps=steps)

        if intent == IntentType.CODE_AND_TOOL:
            steps = [
                PlanStep(
                    step_id=1,
                    description="Execute code snippet or script in sandboxed python environment.",
                    tool_name="python_executor",
                    tool_arguments={"code": message},
                ),
                PlanStep(
                    step_id=2,
                    description="Analyze program output and deliver formatted solution.",
                    tool_name=None,
                    depends_on=[1],
                ),
            ]
            return Plan(intent=intent, reasoning="Sandboxed execution then report.", steps=steps)

        # Default multi-step fallback
        steps = [
            PlanStep(
                step_id=1,
                description="Gather evidence and query internal knowledge.",
                tool_name="document_search",
                tool_arguments={"query": message},
            ),
            PlanStep(
                step_id=2,
                description="Evaluate findings and complete task.",
                tool_name=None,
                depends_on=[1],
            ),
        ]
        return Plan(intent=intent, reasoning="Gather evidence then formulate response.", steps=steps)
